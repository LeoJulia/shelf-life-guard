/**
 * Пауза бездействия, после которой изменённый вручную порядок позиций пишется
 * в БД. Пока пользователь двигает средства, изменения живут только в состоянии
 * компонента — иначе каждый клик означал бы перезапись position у всех позиций.
 */
export const ROUTINE_ORDER_SAVE_DELAY_MS = 30_000;

/**
 * Сколько раз подряд автосохранение пробует повторить запись после сбоя, прежде
 * чем оставить решение пользователю (кнопка «Повторить»). Пауза между попытками
 * растёт экспоненциально от ROUTINE_ORDER_RETRY_BASE_DELAY_MS, чтобы кратковременный
 * обрыв сети успел восстановиться, а постоянная ошибка не долбила сервер.
 */
export const ROUTINE_ORDER_MAX_RETRIES = 3;
export const ROUTINE_ORDER_RETRY_BASE_DELAY_MS = 2_000;
